// Public API helper functions
export function getQuestionsByChapter(chapterId: number, count = 100): QuizQuestion[] {
  const chapterQuestions = FULL_1000_QUESTION_BANK[chapterId] || FULL_1000_QUESTION_BANK[1];
  if (count >= chapterQuestions.length) {
    return chapterQuestions;
  }
  return chapterQuestions.slice(0, count);
}

